#!/usr/bin/env python3
"""
parse_sysbench.py
=================
Experiment 2: Sysbench Memory Benchmark Parser & Performance Delta Calculator

Parses raw log files generated by sysbench memory benchmarks across
Virtual Machine and Docker Container environments, computes statistical summaries
(Mean, Sample Standard Deviation), and outputs a comparative delta breakdown.
"""

import glob
import os
import re
import statistics as stats
import sys

# Regular expressions targeted for Sysbench 1.0.x output metrics
METRIC_PATTERNS = {
    "total_ops": (r"Total operations:\s*(\d+)", int),
    "ops_per_sec": (r"Total operations:\s*\d+\s*\(([\d\.]+)\s*per second\)", float),
    "throughput_mib_s": (r"\(([\d\.]+)\s*MiB/sec\)", float),
    "total_time_s": (r"total time:\s*([\d\.]+)s", float),
    "latency_min_ms": (r"min:\s*([\d\.]+)", float),
    "latency_avg_ms": (r"avg:\s*([\d\.]+)", float),
    "latency_max_ms": (r"max:\s*([\d\.]+)", float),
    "latency_p95_ms": (r"95th percentile:\s*([\d\.]+)", float),
    "latency_sum_ms": (r"sum:\s*([\d\.]+)", float),
}


def parse_sysbench_log(file_path):
    """Reads a single Sysbench benchmark text log and extracts numerical metrics."""
    with open(file_path, "r", encoding="utf-8", errors="replace") as f:
        text = f.read()

    metrics = {}
    for key, (pattern, cast_fn) in METRIC_PATTERNS.items():
        match = re.search(pattern, text)
        if match:
            metrics[key] = cast_fn(match.group(1))
        else:
            metrics[key] = None
    return metrics


def analyze_test_environment(env_name, base_dir):
    """Processes all raw benchmark run logs for a designated test environment."""
    log_dir = os.path.join(base_dir, "results", "raw", "memory", env_name)
    log_files = sorted(glob.glob(os.path.join(log_dir, "run_*.txt")))

    if not log_files:
        print(f"[-] No benchmark log files located in: {log_dir}")
        return None

    parsed_records = [parse_sysbench_log(p) for p in log_files]
    count = len(parsed_records)

    print("\n" + "=" * 65)
    print(f" Environment Telemetry: {env_name.upper()} ({count} run(s) analyzed)")
    print("=" * 65)

    summary = {}
    for metric_name in METRIC_PATTERNS:
        valid_values = [r[metric_name] for r in parsed_records if r[metric_name] is not None]
        if not valid_values:
            continue
        mean_val = stats.mean(valid_values)
        stdev_val = stats.stdev(valid_values) if len(valid_values) > 1 else 0.0
        summary[metric_name] = {"mean": mean_val, "stddev": stdev_val, "data": valid_values}
        print(f"  {metric_name:<20} | Mean = {mean_val:>12.4f} | StdDev = {stdev_val:>10.4f}")

    return summary


def main():
    script_dir = os.path.dirname(os.path.abspath(__file__))
    base_dir = os.path.dirname(script_dir)

    print("=================================================================")
    print(" Experiment 2: Automated Sysbench Memory Log Parser")
    print("=================================================================")

    vm_stats = analyze_test_environment("vm", base_dir)
    container_stats = analyze_test_environment("container", base_dir)

    if vm_stats and container_stats:
        print("\n" + "#" * 65)
        print(" Comparative Analysis: Docker Container vs. Virtual Machine")
        print("#" * 65)

        # Throughput comparison
        vm_tp = vm_stats["throughput_mib_s"]["mean"]
        ct_tp = container_stats["throughput_mib_s"]["mean"]
        tp_delta = ct_tp - vm_tp
        tp_pct = (tp_delta / vm_tp) * 100.0

        # Execution time comparison
        vm_time = vm_stats["total_time_s"]["mean"]
        ct_time = container_stats["total_time_s"]["mean"]
        time_delta = ct_time - vm_time
        time_pct = (time_delta / vm_time) * 100.0

        # Max latency spike comparison
        vm_lat = vm_stats["latency_max_ms"]["mean"]
        ct_lat = container_stats["latency_max_ms"]["mean"]
        lat_delta = ct_lat - vm_lat
        lat_pct = (lat_delta / vm_lat) * 100.0

        print(f"  Memory Bandwidth (MiB/s):")
        print(f"    VM:        {vm_tp:>12.2f} MiB/s")
        print(f"    Container: {ct_tp:>12.2f} MiB/s")
        print(f"    Variance:  {tp_delta:>+12.2f} MiB/s ({tp_pct:+.2f}%)\n")

        print(f"  Total Wall-Clock Time (s):")
        print(f"    VM:        {vm_time:>12.4f} s")
        print(f"    Container: {ct_time:>12.4f} s")
        print(f"    Variance:  {time_delta:>+12.4f} s ({time_pct:+.2f}%)\n")

        print(f"  Peak Latency Jitter (ms):")
        print(f"    VM:        {vm_lat:>12.2f} ms")
        print(f"    Container: {ct_lat:>12.2f} ms")
        print(f"    Variance:  {lat_delta:>+12.2f} ms ({lat_pct:+.2f}%)")
        print("#" * 65 + "\n")


if __name__ == "__main__":
    main()
